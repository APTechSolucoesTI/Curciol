if (!class_exists('TApplication')) { class TApplication extends AdiantiCoreApplication {} }

function auditarTeste(): void { $a = new Agendamento(); $a->id = 1; SystemChangeLogService::register($a, [], ['observacao' => 'TESTE AUDITORIA ISOLADA']); }

$logInfo = TConnection::getDatabaseInfo('log');
$escritorioInfo = TConnection::getDatabaseInfo('escritorio');
$isolado = $escritorioInfo;
unset($isolado['slog']);
if (isset($argv[1]) && preg_match('/^teste_log_[0-9]+$/', $argv[1])) {
    TConnection::setDatabaseInfo('log', array_merge($isolado, ['keep' => 0, 'opts' => "options='-c search_path={$argv[1]}'"]));
    TTransaction::open('escritorio');
    for ($i = 0; $i < 12; $i++) {
        (new SystemSqlLogService())->write('INSERT INTO teste VALUES (1)');
        SystemAccessLogService::registerLogin();
        auditarTeste();
    }
    TTransaction::rollback();
    exit;
}
$schema = 'teste_log_' . getmypid();
$admin = TConnection::openArray(array_merge($isolado, ['keep' => 0]));
$admin->exec("CREATE SCHEMA {$schema}");
foreach (['system_sql_log', 'system_access_log', 'system_change_log'] as $table) {
    $columns = $table === 'system_sql_log'
        ? 'logdate,log_year,log_month,log_day,login,database_name,sql_command,statement_type,access_ip,transaction_id,log_trace,session_id,class_name,php_sapi,request_id'
        : 'sessionid,login,login_time,login_year,login_month,login_day,impersonated,impersonated_by,access_ip,logout_time';
    if ($table === 'system_change_log') { $columns = 'tablename,logdate,log_year,log_month,log_day,login,primarykey,pkvalue,operation,columnname,oldvalue,newvalue,access_ip,transaction_id,log_trace,session_id,class_name,php_sapi'; }
    $definitions = implode(', ', array_map(fn($c) => $c . ' text', explode(',', $columns)));
    $admin->exec("CREATE TABLE {$schema}.{$table} (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, {$definitions})");
    $admin->exec("ALTER TABLE {$schema}.{$table} ADD CONSTRAINT falha_de_teste CHECK (false)");
}
$ruim = array_merge($isolado, ['keep' => 0, 'opts' => "options='-c search_path={$schema}'"]);
TSession::setValue('login', 'TESTE LOG ISOLADO');

try {
    foreach (['sql', 'login', 'auditoria', 'logout'] as $tipo) {
        TTransaction::open('escritorio');
        $principal = TTransaction::get();
        $principal->exec('CREATE TEMP TABLE prova_operacao (id integer) ON COMMIT DROP');
        $principal->exec('INSERT INTO prova_operacao VALUES (1)');
        TConnection::setDatabaseInfo('log', $ruim);
        try {
            if ($tipo === 'sql') { (new SystemSqlLogService())->write('INSERT INTO teste VALUES (1)'); }
            if ($tipo === 'auditoria') { auditarTeste(); }
            if ($tipo === 'login') { SystemAccessLogService::registerLogin(); }
            if ($tipo === 'logout') {
                // SELECT falha: a tabela de logout esta ausente neste search_path.
                $admin->exec("ALTER TABLE {$schema}.system_access_log RENAME TO acesso_indisponivel");
                SystemAccessLogService::registerLogout();
            }
            ok("{$tipo}: falha do log nao escapa", true);
        } catch (Throwable $e) {
            ok("{$tipo}: falha do log nao escapa", false, get_class($e));
        }
        igual("{$tipo}: conexao principal preservada", true, TTransaction::get() === $principal);
        igual("{$tipo}: operacao principal continua valida", 1, (int) $principal->query('SELECT count(*) FROM prova_operacao')->fetchColumn());
        while (TTransaction::get()) { TTransaction::rollback(); }
        TConnection::setDatabaseInfo('log', $logInfo);
    }

    // Falha ao conectar tambem nao deve alterar a pilha do Adianti.
    TTransaction::open('escritorio');
    $principal = TTransaction::get();
    TConnection::setDatabaseInfo('log', array_merge($logInfo, ['type' => 'inexistente']));
    try { (new SystemSqlLogService())->write('UPDATE teste SET id = 1'); ok('conexao indisponivel: nao escapa', true); }
    catch (Throwable $e) { ok('conexao indisponivel: nao escapa', false, get_class($e)); }
    igual('conexao indisponivel: pilha preservada', true, TTransaction::get() === $principal);
    while (TTransaction::get()) { TTransaction::rollback(); }
    $admin->exec("ALTER TABLE {$schema}.acesso_indisponivel RENAME TO system_access_log");
    foreach (['system_sql_log', 'system_access_log', 'system_change_log'] as $table) {
        $admin->exec("ALTER TABLE {$schema}.{$table} DROP CONSTRAINT falha_de_teste");
    }
    // Dois processos reais gravam SQL e acesso simultaneamente no schema descartavel.
    $processos = [];
    for ($i = 0; $i < 2; $i++) {
        $processos[] = proc_open([PHP_BINARY, __FILE__, $schema], [0 => ['file', '/dev/null', 'r'], 1 => ['file', '/dev/null', 'w'], 2 => ['file', '/dev/null', 'w']], $pipes);
    }
    foreach ($processos as $p) { igual('gravador concorrente terminou', 0, proc_close($p)); }
    // log de SQL desligado em 09/11/2026 (SystemSqlLogService nao grava mais nada)
    igual('system_sql_log: desligado, nada gravado', 0, (int) $admin->query("SELECT count(*) FROM {$schema}.system_sql_log")->fetchColumn());
    foreach (['system_access_log', 'system_change_log'] as $table) {
        igual($table . ': todos os logs concorrentes persistem', 24, (int) $admin->query("SELECT count(*) FROM {$schema}.{$table}")->fetchColumn());
        igual($table . ': IDs distintos', 24, (int) $admin->query("SELECT count(DISTINCT id) FROM {$schema}.{$table}")->fetchColumn());
    }
    TConnection::setDatabaseInfo('log', $ruim);
    SystemAccessLogService::registerLogout();
    igual('logout atualiza somente a ultima sessao', 1, (int) $admin->query("SELECT count(*) FROM {$schema}.system_access_log WHERE logout_time IS NOT NULL")->fetchColumn());

} finally {
    // A versao defeituosa pode deixar um slot sem PDO no topo da pilha.
    TConnection::setDatabaseInfo('log', $logInfo);
    while (TTransaction::get()) { TTransaction::rollback(); }
    $admin->exec("DROP SCHEMA {$schema} CASCADE");
}
fim();
